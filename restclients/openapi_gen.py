"""Generate a small client (and its models) from an OpenAPI description.

``generate_client(spec)`` returns Python source containing

* a dataclass for every object schema in ``components/schemas``, based on
  :class:`restclients.models.Model` (so responses are validated when decoded), and
* a subclass of :class:`restclients.base.ApiClient` with one method per operation.

Method conventions:

* path parameters (and other required ones) are positional, optional ones are
  arguments defaulting to ``None`` that are left out of the request when ``None``;
* a request body is the ``body`` argument and is sent as JSON (a model instance
  is sent without its unset fields);
* the method returns a model (or list of models) when the success response refers
  to an object schema, otherwise the decoded JSON, and ``None`` for an empty body.

It is a few hundred lines rather than openapi-generator, and handles the common
shapes only: JSON bodies, local ``$ref``s, no auth schemes, no cookies, no
recursive schemas.
"""
import keyword
import re

from restclients.openapi import SpecError

HEADER = '''"""Client for {title} {version}.

Generated by restclients.openapi_gen. Edit the spec, not this file.
"""
from dataclasses import dataclass
from typing import Any, Dict, List, Optional
from urllib.parse import quote

from restclients.base import ApiClient
from restclients.models import Model
from restclients.validation import parse, parse_list


def _q(value):
    return quote(str(value), safe="")


'''

_SCALARS = {"integer": "int", "number": "float", "string": "str", "boolean": "bool"}
_REF_PREFIX = "#/components/schemas/"


def snake_case(name):
    """``getOrderById`` -> ``get_order_by_id``; also cleans up punctuation."""
    name = re.sub(r"[^0-9A-Za-z]+", "_", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name).lower().strip("_")
    if not name or name[0].isdigit():
        name = "_" + name
    if keyword.iskeyword(name) or name in ("self", "body"):
        name += "_"
    return name


def class_name(title):
    words = re.findall(r"[A-Za-z0-9]+", title)
    return "".join(w[:1].upper() + w[1:] for w in words) + "Client" if words else "ApiClientImpl"


def _unique(names):
    seen, out = {}, []
    for name in names:
        count = seen.get(name, 0)
        seen[name] = count + 1
        out.append(name if count == 0 else "%s_%d" % (name, count + 1))
    return out


# -- models -------------------------------------------------------------------

def _ref_name(schema):
    ref = schema.get("$ref") if isinstance(schema, dict) else None
    if ref is None:
        return None
    if not ref.startswith(_REF_PREFIX):
        raise SpecError("only %s... references are supported, got %r" % (_REF_PREFIX, ref))
    return ref[len(_REF_PREFIX):]


def _is_model(schema):
    """True for object schemas with properties, which become dataclasses."""
    return (isinstance(schema, dict) and schema.get("type", "object") == "object"
            and bool(schema.get("properties")))


def python_type(schema, models):
    """The annotation text for a JSON schema; ``models`` is the set of dataclass names."""
    if not isinstance(schema, dict) or not schema:
        return "Any"
    ref = _ref_name(schema)
    if ref is not None:
        return ref if ref in models else "Any"
    kind = schema.get("type")
    if kind in _SCALARS:
        return _SCALARS[kind]
    if kind == "array":
        return "List[%s]" % python_type(schema.get("items"), models)
    return "Dict[str, Any]" if kind == "object" else "Any"


def _dependencies(schema):
    found = set()
    if isinstance(schema, dict):
        ref = _ref_name(schema)
        if ref:
            found.add(ref)
        for value in schema.values():
            if isinstance(value, dict):
                found |= _dependencies(value)
    return found


def _ordered_models(schemas):
    """Model names with dependencies first. Recursive schemas are not supported."""
    models = {n for n, s in schemas.items() if _is_model(s)}
    order, state = [], {}

    def visit(name):
        if state.get(name) == "done":
            return
        if state.get(name) == "visiting":
            raise SpecError("recursive schema %r is not supported" % name)
        state[name] = "visiting"
        for dep in sorted(_dependencies(schemas[name]) & models):
            visit(dep)
        state[name] = "done"
        order.append(name)

    for name in sorted(models):
        visit(name)
    return order


def _field_lines(name, schema, models):
    required = set(schema.get("required", []))
    required_fields, optional_fields = [], []
    for prop, prop_schema in schema["properties"].items():
        if not prop.isidentifier() or keyword.iskeyword(prop):
            raise SpecError("property %r of %s cannot be a dataclass field" % (prop, name))
        annotation = python_type(prop_schema, models)
        nullable = isinstance(prop_schema, dict) and prop_schema.get("nullable")
        if prop in required:
            if nullable:
                annotation = "Optional[%s]" % annotation
            required_fields.append("    %s: %s" % (prop, annotation))
        elif isinstance(prop_schema, dict) and "default" in prop_schema and not nullable:
            optional_fields.append("    %s: %s = %r" % (prop, annotation, prop_schema["default"]))
        else:
            optional_fields.append("    %s: Optional[%s] = None" % (prop, annotation))
    return required_fields + optional_fields


def generate_models(spec):
    """Dataclass source for every object schema in the spec (empty string if none)."""
    order = _ordered_models(spec.schemas)
    models = set(order)
    blocks = []
    for name in order:
        if not name.isidentifier() or keyword.iskeyword(name):
            raise SpecError("schema name %r is not a valid Python class name" % name)
        schema = spec.schemas[name]
        lines = ["@dataclass", "class %s(Model):" % name]
        if schema.get("description"):
            lines.append('    """%s"""' % schema["description"].replace('"', "'"))
        lines += _field_lines(name, schema, models)
        blocks.append("\n".join(lines))
    return "\n\n\n".join(blocks)


# -- operations ---------------------------------------------------------------

def _path_expression(path, arg_for):
    """``/orders/{orderId}`` -> (``'/orders/%s'``, ``(_q(order_id),)``)."""
    names = re.findall(r"\{([^}]+)\}", path)
    if not names:
        return repr(path), None
    template = re.sub(r"\{[^}]+\}", "\0", path).replace("%", "%%").replace("\0", "%s")
    args = ", ".join("_q(%s)" % arg_for[n] for n in names)
    return repr(template), "(%s,)" % args


def _return_expression(op, models):
    """How to turn the raw JSON into the declared return value (None: return it as is)."""
    schema = op.success_schema
    ref = _ref_name(schema) if schema else None
    if ref in models:
        return "parse(%s, raw)" % ref
    if schema and schema.get("type") == "array":
        item_ref = _ref_name(schema.get("items") or {})
        if item_ref in models:
            return "parse_list(%s, raw)" % item_ref
    return None


def _method_source(op, method_name, models):
    ordered = sorted(op.parameters, key=lambda p: not p.required)
    names = _unique([snake_case(p.name) for p in ordered])
    arg_for = {}                      # parameter name as written in the spec -> python name
    for p, n in zip(ordered, names):
        arg_for.setdefault(p.name, n)
    positional = [n for p, n in zip(ordered, names) if p.required]
    optional = [n for p, n in zip(ordered, names) if not p.required]
    body = op.request_body
    if body is not None:
        (positional if body["required"] else optional).append("body")
    signature = ["self"] + positional + ["%s=None" % n for n in optional]

    doc = op.summary or "%s %s" % (op.method, op.path)
    lines = ["    def %s(%s):" % (method_name, ", ".join(signature)),
             '        """%s"""' % doc.replace('"', "'")]
    path_expr, path_args = _path_expression(op.path, arg_for)
    target = "%s %% %s" % (path_expr, path_args) if path_args else path_expr
    call = ["self._call(%r, %s" % (op.method, target)]
    for location, keyword_name in (("query", "params"), ("header", "headers")):
        chosen = [(p.name, n) for p, n in zip(ordered, names) if p.location == location]
        if chosen:
            call.append(", %s={%s}" % (keyword_name, ", ".join("%r: %s" % c for c in chosen)))
    if body is not None:
        call.append(", body=body")
    call.append(")")
    returned = _return_expression(op, models)
    if returned:
        lines.append("        raw = " + "".join(call))
        lines.append("        return " + returned)
    else:
        lines.append("        return " + "".join(call))
    return "\n".join(lines)


def generate_client(spec, name=None):
    """Python source for the models and a client class covering every operation in ``spec``."""
    cls = name or class_name(spec.title)
    models = set(_ordered_models(spec.schemas))
    out = [HEADER.format(title=spec.title or "the API", version=spec.version or "")]
    model_source = generate_models(spec)
    if model_source:
        out.append(model_source + "\n\n\n")
    out.append("class %s(ApiClient):" % cls)
    if spec.base_url:
        out.append("    default_base_url = %r\n" % spec.base_url)
    method_names = _unique([snake_case(op.operation_id) for op in spec.operations])
    methods = [_method_source(op, n, models) for op, n in zip(spec.operations, method_names)]
    out.append("\n\n".join(methods) if methods else "    pass")
    return "\n".join(out) + "\n"
